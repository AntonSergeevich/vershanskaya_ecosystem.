class Command(BaseCommand):
    help = "Создаёт черновики оферты и политики (требуют вычитки юристом)."

    def handle(self, *args, **options):
        created = 0
        for draft in DRAFTS:
            _, is_new = LegalPage.objects.get_or_create(
                slug=draft['slug'],
                defaults={**draft, 'is_published': False},
            )
            created += int(is_new)
            if not is_new and options['verbosity']:
                self.stdout.write(f"«{draft['title']}» уже есть — не трогаю.")

        if options['verbosity']:
            self.stdout.write(self.style.SUCCESS(f"Создано черновиков: {created}."))
            self.stdout.write(self.style.WARNING(
                "Это рыба, а не готовые документы. Заполните Реквизиты, отдайте "
                "тексты юристу и только потом ставьте галочку «Опубликован»."))
